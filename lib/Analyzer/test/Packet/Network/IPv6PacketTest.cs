    private static readonly IAnalysisConfiguration Configuration = new DefaultTrafficAnalysisConfiguration(new SessionMetadata());
    private static readonly PacketContentReader PacketContentReader = new(Configuration);

    [Fact]
    public void Test_IPv6PacketParse()
    {
        // Given
        var ethernetFrame = EthernetFrame.Parse(TcpIpPacket, TcpIpPacket.Length, PacketContentReader);

        // Then
        Assert.NotNull(ethernetFrame.NetworkPacket);
        Assert.True(ethernetFrame.NetworkPacket is IpPacket);

        var ipv6Packet = (IPv6Packet)ethernetFrame.NetworkPacket;

        ipv6Packet.Should().NotBeNull();
        ipv6Packet.IpProtocol.Should().Be(IpProtocol.TCP);
        ipv6Packet.SourceAddress.ToString().Should().Be("2a01:110:8:3b:94a3:ccae:482d:9564");
        ipv6Packet.DestinationAddress.ToString().Should().Be("2a01:111:f100:3000::a83e:1b36");
        ipv6Packet.Version.Should().Be(6);
        ipv6Packet.PayloadLength.Should().Be(737);
        ipv6Packet.TrafficClass.Should().Be(DscpValue.DF);
        ipv6Packet.EcnCode.Should().Be(EcnCode.EctCapable_0);
        ipv6Packet.HopLimit.Should().Be(64);
        ipv6Packet.FlowLabel.Should().Be(0x448a8);
    }

    [Fact]
    public void Test_IPv6HopbyHopPacketParse()
    {
        // Given
        var ipv6Packet = IPv6Packet.Parse(HopbyHopPacket, 14, HopbyHopPacket.Length, PacketContentReader);

        // Then

        ipv6Packet.Should().NotBeNull();
        ipv6Packet.IpProtocol.Should().Be(IpProtocol.ICMPv6);
        ipv6Packet.SourceAddress.ToString().Should().Be("fe80::f43e:e453:7006:66a9");
        ipv6Packet.DestinationAddress.ToString().Should().Be("ff02::16");
        ipv6Packet.Version.Should().Be(6);
        ipv6Packet.PayloadLength.Should().Be(36);
        ipv6Packet.TrafficClass.Should().Be(DscpValue.DF);
        ipv6Packet.EcnCode.Should().Be(EcnCode.NonEct);
        ipv6Packet.HopLimit.Should().Be(1);
        ipv6Packet.FlowLabel.Should().Be(0x0);
    }


